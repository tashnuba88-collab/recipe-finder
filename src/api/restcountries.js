export async function getCountry(code, signal) {
  const fields = "name,flags,capital,region,subregion,population,languages,currencies";
  const res = await fetch(`${BASE}/alpha/${code}?fields=${fields}`, { signal });
  if (!res.ok) throw new Error(`Country request failed (${res.status})`);
  const data = await res.json();
  return Array.isArray(data) ? data[0] : data;
}
